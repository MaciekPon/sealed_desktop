//! Pure-Rust MiMC over BN254 (Fr), Miyaguchi-Preneel mode. Ported from
//! `sealed_app/lib/infra/zk/mimc_bn254.dart` (round constants from
//! `mimc_constants.dart`; `bytes_to_fr` from `poseidon.dart`).
//!
//! Mirrors go-algorand's `mimc BN254Mp110` opcode (gnark-crypto
//! ecc/bn254/fr/mimc), `circuits/mimc_bn254.circom`, and the web client's
//! mimc-bn254.ts byte-for-byte. Used to compute the deposit leaf + redeem
//! nullifier client-side (see `zk::mimc_tree`). Any divergence breaks
//! on-chain leaves / proofs — the golden-vector tests below guard this
//! against the same committed vectors `mimc_bn254_test.dart` uses.
//!
//! Spec: p = BN254 Fr, 110 rounds, S-box x^5, Miyaguchi-Preneel over 32-byte
//! big-endian blocks. Round constants: legacy keccak256 chain (c[0] =
//! keccak256(keccak256("seed")) mod p). `encrypt(m, key=h)`: for i in 0..110
//! `{ m = (m + h + c[i])^5 }` return `m + h`. Per block: `h = encrypt(m_i, h)
//! + h + m_i`.
//!
//! **Not wired into any Tauri command or the redeem flow yet** — this is
//! Phase 6's foundational step only (see the plan file). Witness
//! generation, SNARK proving, and on-chain wiring are explicitly out of
//! scope here.

